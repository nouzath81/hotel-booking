
CREATE TABLE IF NOT EXISTS users (
 id SERIAL PRIMARY KEY, username VARCHAR(100) UNIQUE NOT NULL,
 password_hash TEXT NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'staff', created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS settings (setting_key VARCHAR(100) PRIMARY KEY, setting_value TEXT);
CREATE TABLE IF NOT EXISTS room_types (
 id SERIAL PRIMARY KEY, type_name VARCHAR(100) UNIQUE NOT NULL, total_rooms INTEGER NOT NULL DEFAULT 0, default_rate NUMERIC(12,2) NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS hotel_rooms (
 id SERIAL PRIMARY KEY, room_no VARCHAR(50) UNIQUE NOT NULL, room_type TEXT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'Active', created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS bookings (
 id SERIAL PRIMARY KEY, booking_no VARCHAR(50) UNIQUE NOT NULL, customer_name TEXT NOT NULL, phone TEXT, whatsapp_no VARCHAR(32), email TEXT, address TEXT,
 room_type TEXT, room_no TEXT, room_count INTEGER NOT NULL DEFAULT 1, checkin_date DATE NOT NULL, checkout_date DATE NOT NULL,
 nights INTEGER NOT NULL DEFAULT 1, rate_per_night NUMERIC(12,2) NOT NULL DEFAULT 0, extra_charges NUMERIC(12,2) NOT NULL DEFAULT 0,
 discount NUMERIC(12,2) NOT NULL DEFAULT 0, tax_percent NUMERIC(8,2) NOT NULL DEFAULT 0, advance_paid NUMERIC(12,2) NOT NULL DEFAULT 0,
 status VARCHAR(20) NOT NULL DEFAULT 'Confirmed', notes TEXT, created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS bank_accounts (
 id SERIAL PRIMARY KEY, bank_name VARCHAR(200) NOT NULL, account_name VARCHAR(200), account_no VARCHAR(100) NOT NULL,
 branch VARCHAR(150), account_type VARCHAR(50) DEFAULT 'Bank', active INTEGER NOT NULL DEFAULT 1, created_at TIMESTAMPTZ DEFAULT NOW(),
 UNIQUE(bank_name,account_no)
);
CREATE TABLE IF NOT EXISTS payments (
 id SERIAL PRIMARY KEY, booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE, payment_date DATE NOT NULL,
 amount NUMERIC(12,2) NOT NULL DEFAULT 0, method TEXT, bank_account_id INTEGER REFERENCES bank_accounts(id) ON DELETE SET NULL,
 reference_no VARCHAR(100), notes TEXT, created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS petty_cash (
 id SERIAL PRIMARY KEY, entry_date DATE NOT NULL, description TEXT NOT NULL, category TEXT,
 type VARCHAR(20) NOT NULL DEFAULT 'Out', amount NUMERIC(12,2) NOT NULL DEFAULT 0, created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS pos_products (
 id SERIAL PRIMARY KEY, name TEXT NOT NULL, sku TEXT, category TEXT, price NUMERIC(12,2) NOT NULL DEFAULT 0,
 stock_qty INTEGER NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 1, created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS pos_sales (
 id SERIAL PRIMARY KEY, sale_no VARCHAR(50) UNIQUE NOT NULL, customer_name TEXT, subtotal NUMERIC(12,2) NOT NULL DEFAULT 0,
 discount NUMERIC(12,2) NOT NULL DEFAULT 0, tax_percent NUMERIC(8,2) NOT NULL DEFAULT 0, tax_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
 total NUMERIC(12,2) NOT NULL DEFAULT 0, payment_method VARCHAR(20) NOT NULL DEFAULT 'Cash', amount_tendered NUMERIC(12,2) NOT NULL DEFAULT 0,
 change_due NUMERIC(12,2) NOT NULL DEFAULT 0, cashier TEXT, notes TEXT, booking_id INTEGER, voided INTEGER NOT NULL DEFAULT 0, created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS pos_sale_items (
 id SERIAL PRIMARY KEY, sale_id INTEGER NOT NULL REFERENCES pos_sales(id) ON DELETE CASCADE, product_id INTEGER,
 product_name TEXT NOT NULL, unit_price NUMERIC(12,2) NOT NULL DEFAULT 0, qty INTEGER NOT NULL DEFAULT 1, line_total NUMERIC(12,2) NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS pos_accounts (
 id SERIAL PRIMARY KEY, account_name VARCHAR(100) UNIQUE NOT NULL, account_type VARCHAR(20) NOT NULL DEFAULT 'Cash',
 opening_balance NUMERIC(12,2) NOT NULL DEFAULT 0, active INTEGER NOT NULL DEFAULT 1, created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS maintenance_tickets (
 id SERIAL PRIMARY KEY, room_no VARCHAR(50), title TEXT NOT NULL, priority VARCHAR(20) NOT NULL DEFAULT 'Medium',
 status VARCHAR(20) NOT NULL DEFAULT 'Open', reported_by VARCHAR(100), resolved_at TIMESTAMPTZ NULL
);
